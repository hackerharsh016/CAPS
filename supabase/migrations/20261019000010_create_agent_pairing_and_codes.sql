-- 1. Table for single-use short-lived agent pairing codes
CREATE TABLE IF NOT EXISTS public.agent_pairing_codes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    shop_id UUID NOT NULL REFERENCES public.shops(id) ON DELETE CASCADE,
    code TEXT NOT NULL UNIQUE,
    created_by UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    is_used BOOLEAN NOT NULL DEFAULT false,
    used_at TIMESTAMPTZ,
    used_by_device_id UUID REFERENCES public.agent_devices(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Ensure all columns exist even if table was pre-created in an earlier migration
ALTER TABLE public.agent_pairing_codes
    ADD COLUMN IF NOT EXISTS code TEXT UNIQUE,
    ADD COLUMN IF NOT EXISTS is_used BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS used_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS used_by_device_id UUID REFERENCES public.agent_devices(id) ON DELETE SET NULL;

COMMENT ON TABLE public.agent_pairing_codes IS 'Single-use high-entropy pairing codes with 10-minute TTL generated by shop owners.';
COMMENT ON COLUMN public.agent_pairing_codes.code IS 'Alphanumeric pairing token entered by the Windows print agent operator.';

CREATE INDEX IF NOT EXISTS idx_pairing_codes_code ON public.agent_pairing_codes(code) WHERE is_used = false;
CREATE INDEX IF NOT EXISTS idx_pairing_codes_shop_id ON public.agent_pairing_codes(shop_id);

-- 2. Function: Generate short-lived pairing code
CREATE OR REPLACE FUNCTION public.generate_agent_pairing_code(
    p_shop_id UUID,
    p_created_by UUID,
    p_ttl_seconds INTEGER DEFAULT 600
)
RETURNS TABLE (
    pairing_code_id UUID,
    code TEXT,
    expires_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_code TEXT;
    v_expires TIMESTAMPTZ;
    v_id UUID;
    v_chars TEXT := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ'; -- Exclude ambiguous chars (0, 1, I, O)
    v_len INT := 8;
    v_i INT;
    v_char_idx INT;
BEGIN
    -- Verify shop exists
    IF NOT EXISTS (SELECT 1 FROM public.shops WHERE id = p_shop_id) THEN
        RAISE EXCEPTION 'Shop % not found', p_shop_id USING ERRCODE = 'P0002';
    END IF;

    -- Generate random 8-character string (format: CP-XXXXXX)
    v_code := 'CP-';
    FOR v_i IN 1..6 LOOP
        v_char_idx := 1 + floor(random() * length(v_chars))::integer;
        v_code := v_code || substr(v_chars, v_char_idx, 1);
    END LOOP;

    v_expires := timezone('utc'::text, now()) + (COALESCE(p_ttl_seconds, 600) || ' seconds')::interval;
    v_id := gen_random_uuid();

    INSERT INTO public.agent_pairing_codes (
        id,
        shop_id,
        code,
        created_by,
        expires_at,
        is_used,
        created_at
    ) VALUES (
        v_id,
        p_shop_id,
        v_code,
        p_created_by,
        v_expires,
        false,
        timezone('utc'::text, now())
    );

    RETURN QUERY
    SELECT v_id, v_code, v_expires;
END;
$$;

COMMENT ON FUNCTION public.generate_agent_pairing_code IS 'Generates an ephemeral 8-character pairing code for Windows agent enrollment.';

-- 3. Function: Consume pairing code and bind device credentials
CREATE OR REPLACE FUNCTION public.consume_agent_pairing_code(
    p_code TEXT,
    p_device_fingerprint TEXT,
    p_device_name TEXT,
    p_agent_version TEXT,
    p_auth_token_hash TEXT
)
RETURNS TABLE (
    device_id UUID,
    shop_id UUID,
    device_name TEXT,
    paired_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_pairing RECORD;
    v_device_id UUID;
    v_now TIMESTAMPTZ := timezone('utc'::text, now());
BEGIN
    -- 1. Lock and validate pairing code
    SELECT * INTO v_pairing
    FROM public.agent_pairing_codes
    WHERE code = trim(p_code)
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Invalid pairing code %', p_code USING ERRCODE = 'P0002';
    END IF;

    IF v_pairing.is_used THEN
        RAISE EXCEPTION 'Pairing code % has already been consumed', p_code USING ERRCODE = '23514';
    END IF;

    IF v_pairing.expires_at < v_now THEN
        RAISE EXCEPTION 'Pairing code % has expired', p_code USING ERRCODE = '23514';
    END IF;

    -- 2. Register or update agent device
    v_device_id := gen_random_uuid();
    INSERT INTO public.agent_devices (
        id,
        shop_id,
        device_fingerprint,
        device_name,
        agent_version,
        auth_token_hash,
        is_revoked,
        paired_by,
        last_heartbeat_at,
        created_at,
        updated_at
    ) VALUES (
        v_device_id,
        v_pairing.shop_id,
        p_device_fingerprint,
        COALESCE(p_device_name, 'Windows Print Agent'),
        COALESCE(p_agent_version, '0.1.0'),
        p_auth_token_hash,
        false,
        v_pairing.created_by,
        v_now,
        v_now,
        v_now
    );

    -- 3. Mark pairing code used
    UPDATE public.agent_pairing_codes
    SET is_used = true,
        used_at = v_now,
        used_by_device_id = v_device_id
    WHERE id = v_pairing.id;

    RETURN QUERY
    SELECT v_device_id, v_pairing.shop_id, COALESCE(p_device_name, 'Windows Print Agent'), v_now;
END;
$$;

COMMENT ON FUNCTION public.consume_agent_pairing_code IS 'Atomically consumes a pairing code and enrolls the agent device without leaking master secrets.';
