-- ------------------------------------------------------------------------------
-- Agent Devices Policies
-- ------------------------------------------------------------------------------

-- SELECT: Only owning shop owner/members, admin, or the agent device itself
CREATE POLICY "agent_devices_select_owner_or_admin"
    ON public.agent_devices
    FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM public.shops s
            WHERE s.id = agent_devices.shop_id AND (s.owner_id = auth.uid() OR public.is_shop_owner_or_member(s.id))
        )
        OR public.is_admin()
    );

-- INSERT: Only owning shop owner or admin can register a device
CREATE POLICY "agent_devices_insert_owner"
    ON public.agent_devices
    FOR INSERT
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.shops s
            WHERE s.id = agent_devices.shop_id AND s.owner_id = auth.uid()
        )
        OR public.is_admin()
    );

-- UPDATE:
-- 1) Shop owner or admin can update device settings or revoke device
-- 2) Unrevoked agent can update heartbeat/version, but CANNOT unrevoke itself
CREATE POLICY "agent_devices_update_owner_or_agent"
    ON public.agent_devices
    FOR UPDATE
    USING (
        EXISTS (
            SELECT 1 FROM public.shops s
            WHERE s.id = agent_devices.shop_id AND s.owner_id = auth.uid()
        )
        OR public.is_admin()
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.shops s
            WHERE s.id = agent_devices.shop_id AND s.owner_id = auth.uid()
        )
        OR public.is_admin()
    );

-- DELETE: Only owning shop owner or admin can unregister an agent device
CREATE POLICY "agent_devices_delete_owner"
    ON public.agent_devices
    FOR DELETE
    USING (
        EXISTS (
            SELECT 1 FROM public.shops s
            WHERE s.id = agent_devices.shop_id AND s.owner_id = auth.uid()
        )
        OR public.is_admin()
    );

