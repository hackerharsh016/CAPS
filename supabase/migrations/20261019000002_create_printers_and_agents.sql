-- 1. Custom Domain Enums
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'printer_role') THEN
        CREATE TYPE public.printer_role AS ENUM ('bw', 'color', 'large_format');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'printer_status') THEN
        CREATE TYPE public.printer_status AS ENUM ('online', 'offline', 'busy', 'error');
    END IF;
END $$;

-- 2. Registered Agent Devices Table
-- Physical Windows computers running the CAPS Desktop Print Agent paired to a shop
CREATE TABLE IF NOT EXISTS public.agent_devices (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    shop_id UUID NOT NULL REFERENCES public.shops(id) ON DELETE CASCADE,
    device_fingerprint TEXT NOT NULL,
    device_name TEXT NOT NULL CHECK (char_length(trim(device_name)) >= 1),
    agent_version TEXT NOT NULL DEFAULT '0.1.0',
    auth_token_hash TEXT NOT NULL,
    is_revoked BOOLEAN NOT NULL DEFAULT false,
    revoked_at TIMESTAMPTZ,
    revoked_reason TEXT,
    paired_by UUID NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
    last_heartbeat_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_agent_devices_shop_fingerprint UNIQUE (shop_id, device_fingerprint)
);

COMMENT ON TABLE public.agent_devices IS 'Authenticated Windows machines authorized to receive and execute print jobs for a shop.';
COMMENT ON COLUMN public.agent_devices.is_revoked IS 'Revocation flag; revoked devices are immediately denied heartbeat and claim access.';

-- Trigger for agent_devices updated_at
DROP TRIGGER IF EXISTS trg_agent_devices_updated_at ON public.agent_devices;
CREATE TRIGGER trg_agent_devices_updated_at
    BEFORE UPDATE ON public.agent_devices
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();

-- 3. Agent Sessions Table (Active connections, heartbeats, and telemetry)
CREATE TABLE IF NOT EXISTS public.agent_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id UUID NOT NULL REFERENCES public.agent_devices(id) ON DELETE CASCADE,
    shop_id UUID NOT NULL REFERENCES public.shops(id) ON DELETE CASCADE,
    agent_version TEXT NOT NULL,
    session_status TEXT NOT NULL DEFAULT 'online' CHECK (session_status IN ('online', 'offline')),
    ip_address INET,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    started_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    ended_at TIMESTAMPTZ
);

COMMENT ON TABLE public.agent_sessions IS 'Active and historical connection sessions for desktop print agents.';

-- 4. Agent Pairing Codes Table (Time-bounded pairing verification)
CREATE TABLE IF NOT EXISTS public.agent_pairing_codes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    shop_id UUID NOT NULL REFERENCES public.shops(id) ON DELETE CASCADE,
    code TEXT NOT NULL UNIQUE,
    created_by UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    is_used BOOLEAN NOT NULL DEFAULT false,
    used_at TIMESTAMPTZ,
    used_by_device_id UUID REFERENCES public.agent_devices(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.agent_pairing_codes IS 'Temporary OTP/pairing codes generated by shop owners to authorize desktop agent installation.';

-- 5. Printers Table
-- Physical printers attached to shop PCs, discovered by agent or configured by owner
CREATE TABLE IF NOT EXISTS public.printers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    shop_id UUID NOT NULL REFERENCES public.shops(id) ON DELETE CASCADE,
    device_id UUID REFERENCES public.agent_devices(id) ON DELETE SET NULL,
    name TEXT NOT NULL CHECK (char_length(trim(name)) >= 1),
    role public.printer_role NOT NULL DEFAULT 'bw'::public.printer_role,
    status public.printer_status NOT NULL DEFAULT 'offline'::public.printer_status,
    is_default BOOLEAN NOT NULL DEFAULT false,
    capabilities JSONB NOT NULL DEFAULT '{
        "paper_sizes": ["a4"],
        "color_modes": ["bw"],
        "duplex_supported": false,
        "max_copies": 99
    }'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_shop_printer_name UNIQUE (shop_id, name)
);

COMMENT ON TABLE public.printers IS 'Physical printer devices connected to a shop, with driver capabilities and owner routing role.';
COMMENT ON COLUMN public.printers.capabilities IS 'Reported driver capabilities (paper_sizes, color_modes, duplex_supported, max_copies).';

-- Trigger for printers updated_at
DROP TRIGGER IF EXISTS trg_printers_updated_at ON public.printers;
CREATE TRIGGER trg_printers_updated_at
    BEFORE UPDATE ON public.printers
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();

-- 6. Helper Security Functions
CREATE OR REPLACE FUNCTION public.is_device_unrevoked(target_device_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.agent_devices
        WHERE id = target_device_id AND NOT is_revoked
    );
$$;

