-- SELECT: Customers/public can view printers of open shops (for paper size / color capability discovery);
-- Owners and staff can view all printers for their shops.
CREATE POLICY "printers_select_discovery"
    ON public.printers
    FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM public.shops s
            WHERE s.id = printers.shop_id AND s.status = 'open'::public.shop_status
        )
        OR EXISTS (
            SELECT 1 FROM public.shops s
            WHERE s.id = printers.shop_id AND (s.owner_id = auth.uid() OR public.is_shop_owner_or_member(s.id))
        )
        OR public.is_admin()
    );

-- INSERT: Only owning shop owner, shop member, or system admin.
-- Other-shop printer creation is strictly rejected!
CREATE POLICY "printers_insert_owner"
    ON public.printers
    FOR INSERT
    WITH CHECK (
        (
            EXISTS (
                SELECT 1 FROM public.shops s
                WHERE s.id = printers.shop_id AND (s.owner_id = auth.uid() OR public.is_shop_owner_or_member(s.id))
            )
            AND (printers.device_id IS NULL OR public.is_device_unrevoked(printers.device_id))
        )
        OR public.is_admin()
    );

-- UPDATE:
-- 1) Owning shop owner or admin can update role, default, name, status, capabilities.
-- 2) Requires matching shop ownership: mutating printers of other shops is strictly denied!
-- 3) If an agent device_id is associated, that device must NOT be revoked.
CREATE POLICY "printers_update_owner"
    ON public.printers
    FOR UPDATE
    USING (
        (
            EXISTS (
                SELECT 1 FROM public.shops s
                WHERE s.id = printers.shop_id AND (s.owner_id = auth.uid() OR public.is_shop_owner_or_member(s.id))
            )
            AND (printers.device_id IS NULL OR public.is_device_unrevoked(printers.device_id))
        )
        OR public.is_admin()
    )
    WITH CHECK (
        (
            EXISTS (
                SELECT 1 FROM public.shops s
                WHERE s.id = printers.shop_id AND (s.owner_id = auth.uid() OR public.is_shop_owner_or_member(s.id))
            )
            AND (printers.device_id IS NULL OR public.is_device_unrevoked(printers.device_id))
        )
        OR public.is_admin()
    );

-- DELETE: Only owning shop owner or admin can delete a printer.
