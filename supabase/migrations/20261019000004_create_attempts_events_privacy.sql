-- SELECT:
-- 1) Customer who owns the print job
-- 2) Shop Owner / Operator of the shop owning the job
-- 3) Registered Agent Device paired with that shop
-- 4) Platform Admin
CREATE POLICY "job_attempts_select"
    ON public.job_attempts
    FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM public.print_jobs pj
            WHERE pj.id = job_attempts.job_id AND pj.customer_id = auth.uid()
        )
        OR EXISTS (
            SELECT 1 FROM public.print_jobs pj
            JOIN public.shops s ON s.id = pj.shop_id
            WHERE pj.id = job_attempts.job_id
              AND (s.owner_id = auth.uid() OR public.is_shop_owner_or_member(s.id))
        )
        OR EXISTS (
            SELECT 1 FROM public.print_jobs pj
            JOIN public.agent_devices ad ON ad.shop_id = pj.shop_id
            WHERE pj.id = job_attempts.job_id
              AND ad.id = job_attempts.agent_device_id
              AND ad.is_revoked = false
        )
        OR public.is_admin()
    );

-- INSERT:
-- Shop staff, authorized agent devices, or admin can claim/insert attempts
