-- 6. Privacy & Lifecycle Helper Functions
-- Finds jobs whose documents have expired and need object storage deletion
CREATE OR REPLACE FUNCTION public.get_expired_documents_for_cleanup(p_limit INTEGER DEFAULT 100)
RETURNS TABLE (
    job_id UUID,
    shop_id UUID,
    document_storage_key TEXT,
    document_expires_at TIMESTAMPTZ,
    status public.job_status
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT
        id AS job_id,
        shop_id,
        document_storage_key,
        document_expires_at,
        status
    FROM public.print_jobs
    WHERE document_expires_at <= timezone('utc'::text, now())
      AND document_storage_key != '[PURGED]'
      AND status IN (
          'completed'::public.job_status,
          'failed'::public.job_status,
          'cancelled'::public.job_status,
          'requires_review'::public.job_status
      )
    ORDER BY document_expires_at ASC
    LIMIT p_limit;
$$;

-- Atomic helper: records deletion log and redacts storage key from print_jobs
CREATE OR REPLACE FUNCTION public.log_and_clear_document_storage(
    p_job_id UUID,
    p_deleted_by public.deleted_by_type,
    p_reason public.deletion_reason
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_storage_key TEXT;
    v_log_id UUID;
BEGIN
    SELECT document_storage_key INTO v_storage_key
    FROM public.print_jobs
    WHERE id = p_job_id;

    IF v_storage_key IS NULL OR v_storage_key = '[PURGED]' THEN
        RAISE EXCEPTION 'Print job % not found or document already purged', p_job_id;
    END IF;

    -- Insert deletion audit entry
    INSERT INTO public.document_deletion_logs (job_id, document_storage_key, deleted_by, reason)
    VALUES (p_job_id, v_storage_key, p_deleted_by, p_reason)
    RETURNING id INTO v_log_id;

    -- Redact document_storage_key in print_jobs
    UPDATE public.print_jobs
    SET document_storage_key = '[PURGED]',
        updated_at = timezone('utc'::text, now())
    WHERE id = p_job_id;

    -- Append audit event
    INSERT INTO public.job_events (
        job_id,
        actor_type,
        to_status,
        event_name,
        metadata
    )
    VALUES (
        p_job_id,
        'system'::public.actor_type,
        (SELECT status FROM public.print_jobs WHERE id = p_job_id),
        'document_purged',
        jsonb_build_object(
            'deletion_log_id', v_log_id,
            'deleted_by', p_deleted_by,
            'reason', p_reason
        )
    );

    RETURN v_log_id;
END;
$$;

