    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT chk_job_events_no_sensitive_doc CHECK (
        NOT (
            metadata ? 'document_data' OR
            metadata ? 'raw_document' OR
            metadata ? 'pdf_content' OR
            metadata ? 'payload_base64' OR
            metadata ? 'file_bytes' OR
            metadata ? 'password'
        )
    )
);

COMMENT ON TABLE public.job_events IS 'Immutable chronological audit ledger tracking state transitions and telemetry without sensitive document bytes.';
COMMENT ON COLUMN public.job_events.metadata IS 'Sanitized JSON metadata payload; strictly checked against document binaries and credentials.';

CREATE INDEX IF NOT EXISTS idx_job_events_job_id ON public.job_events(job_id, created_at ASC);
CREATE INDEX IF NOT EXISTS idx_job_events_attempt_id ON public.job_events(attempt_id) WHERE attempt_id IS NOT NULL;

