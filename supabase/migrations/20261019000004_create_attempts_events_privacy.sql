-- 2. Job Attempts Table
-- Atomic leases and execution tracking per job to prevent duplicate physical print output
CREATE TABLE IF NOT EXISTS public.job_attempts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    job_id UUID NOT NULL REFERENCES public.print_jobs(id) ON DELETE CASCADE,
    printer_id UUID REFERENCES public.printers(id) ON DELETE SET NULL,
    agent_device_id UUID REFERENCES public.agent_devices(id) ON DELETE SET NULL,
    lease_token UUID NOT NULL DEFAULT gen_random_uuid(),
    lease_expires_at TIMESTAMPTZ NOT NULL,
    spooler_job_id INTEGER,
    idempotency_key TEXT NOT NULL CHECK (char_length(trim(idempotency_key)) >= 1),
    status public.attempt_status NOT NULL DEFAULT 'leased'::public.attempt_status,
    error_code TEXT,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_job_attempts_idempotency UNIQUE (job_id, idempotency_key)
);

COMMENT ON TABLE public.job_attempts IS 'Atomic agent claims and execution attempts to guarantee single physical printing.';
COMMENT ON COLUMN public.job_attempts.lease_token IS 'Exclusive lease identifier held by the agent during active execution.';
COMMENT ON COLUMN public.job_attempts.spooler_job_id IS 'Local Windows Print Spooler OS job ID for telemetry and status checks.';
COMMENT ON COLUMN public.job_attempts.idempotency_key IS 'Unique token generated by client/agent to prevent duplicate attempt creations.';

